  'General': 'tabGeneral', 'Setup': 'tabSetup', 'Delta': 'tabDelta', 'Braking': 'tabBraking', 'Corner Speed': 'tabCornerSpeed',
  'Laps': 'tabLaps', 'Events': 'tabEvents', 'Adjustments': 'tabAdjustments',
